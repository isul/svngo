package apache

import (
	"fmt"
	"path/filepath"
	"strings"

	"svngo/internal/fsutil"
	"svngo/internal/ipacl"
)

// Behind a reverse proxy Apache only sees the proxy's address. For requests
// from a trusted proxy, mod_remoteip replaces the client address with the
// right-most untrusted X-Forwarded-For entry before any other module runs, so
// the access log, the SVN allow list, the login block map and the address
// mod_proxy appends for the admin server all use the real client.
// RemoteIPInternalProxy also accepts private client addresses (LAN clients).
// The list comes from the environment, so the file is written once at start.

const remoteIPFile = "remoteip.conf"

// RemoteIPFile is the generated mod_remoteip file included by httpd.conf.
func RemoteIPFile(runDir string) string { return filepath.Join(runDir, remoteIPFile) }

// RemoteIPConf renders the mod_remoteip directives; an empty list keeps
// X-Forwarded-For untrusted.
func RemoteIPConf(trusted ipacl.List) string {
	var b strings.Builder
	b.WriteString("# Generated by SvnGo - trusted reverse proxies (SVNGO_TRUSTED_PROXIES). Do not edit.\n")
	if trusted.Empty() {
		b.WriteString("# X-Forwarded-For is not trusted\n")
		return b.String()
	}
	b.WriteString("RemoteIPHeader X-Forwarded-For\n")
	for _, c := range trusted.CIDRs() {
		fmt.Fprintf(&b, "RemoteIPInternalProxy %s\n", c)
	}
	return b.String()
}

// WriteRemoteIP writes the mod_remoteip file; use it before httpd starts.
func WriteRemoteIP(runDir string, trusted ipacl.List) error {
	return fsutil.AtomicWrite(RemoteIPFile(runDir), []byte(RemoteIPConf(trusted)))
}
