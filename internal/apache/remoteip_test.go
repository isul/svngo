func TestRemoteIPConf(t *testing.T) {
	if got := RemoteIPConf(ipacl.List{}); strings.Contains(got, "RemoteIP") {
		t.Fatalf("empty list produced directives: %q", got)
	}
	got := RemoteIPConf(ipacl.MustParse("172.22.0.1, 10.8.0.0/24\nfd00::/8"))
	want := "# Generated by SvnGo - trusted reverse proxies (SVNGO_TRUSTED_PROXIES). Do not edit.\n" +
		"RemoteIPHeader X-Forwarded-For\n" +
		"RemoteIPInternalProxy 172.22.0.1/32\n" +
		"RemoteIPInternalProxy 10.8.0.0/24\n" +
		"RemoteIPInternalProxy fd00::/8\n"
	if got != want {
		t.Fatalf("RemoteIPConf:\n%s\nwant:\n%s", got, want)
	}
}

func TestCheckWritesRemoteIP(t *testing.T) {
	run := t.TempDir()
	out := filepath.Join(t.TempDir(), "seen")
	cfg := &config.Config{RunDir: run, ApacheConf: filepath.Join(run, "httpd.conf"),
		TrustedProxies: ipacl.MustParse("172.22.0.1")}
	cfg.ApacheBin = fakeHttpd(t, `cat "$SVNGO_REMOTEIP_CONF" > `+out)
	if err := New(cfg, logring.New(10)).Check(context.Background()); err != nil {
		t.Fatal(err)
	}
	seen, _ := os.ReadFile(out)
	if string(seen) != RemoteIPConf(cfg.TrustedProxies) {
		t.Fatalf("httpd -t saw %q", seen)
	}
}
