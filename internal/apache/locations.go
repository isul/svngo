package apache

import (
	"context"
	"fmt"
	"path/filepath"
	"strings"

	"svngo/internal/fsutil"
	"svngo/internal/validate"
)

// SVN locations are additional URL paths next to /svn. Each one is a
// <Location /name> block whose SVNParentPath is <repos>/<name>; all blocks
// share the single htpasswd and authz file, which works because repository
// names are unique across locations (mod_authz_svn matches [repo:/path] by the
// repository folder name only). The blocks live in a generated include file
// applied like the IP allow list: test, then graceful restart.

const locationsFile = "svn-locations.conf"

// LocationsFile is the generated <Location> file included by httpd.conf.
func LocationsFile(runDir string) string { return filepath.Join(runDir, locationsFile) }

// LocationsConf renders one <Location> block per location name. The
// directives must stay identical to the /svn block in docker/httpd.conf.
func LocationsConf(names []string) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by SvnGo - SVN locations. Do not edit.\n")
	for _, n := range names {
		if err := validate.LocationName(n); err != nil {
			return "", fmt.Errorf("invalid location name %q", n)
		}
		fmt.Fprintf(&b, `<Location "/%[1]s">
    DAV svn
    SVNParentPath "${SVNGO_REPOS_DIR}/%[1]s"
    SVNListParentPath Off
    SVNPathAuthz short_circuit
    SVNAllowBulkUpdates Prefer
    SVNCacheTextDeltas On
    SVNCacheFullTexts On

    AuthType Basic
    AuthName "SvnGo Subversion"
    AuthBasicProvider file
    AuthUserFile "${SVNGO_CONFIG_DIR}/htpasswd"
    AuthzSVNAccessFile "${SVNGO_CONFIG_DIR}/authz"
    Require valid-user

    LimitRequestBody ${SVNGO_SVN_MAX_BODY}
    LimitXMLRequestBody ${SVNGO_SVN_MAX_XML}
</Location>
`, n)
	}
	return b.String(), nil
}

// WriteLocations writes the locations file; use it before httpd starts.
func WriteLocations(runDir string, names []string) error {
	conf, err := LocationsConf(names)
	if err != nil {
		return err
	}
	return fsutil.AtomicWrite(LocationsFile(runDir), []byte(conf))
}

// ApplyLocations replaces the locations file after `httpd -t` accepted it and
// gracefully restarts a running httpd. On failure nothing changes.
func (ap *Supervisor) ApplyLocations(ctx context.Context, names []string) error {
	conf, err := LocationsConf(names)
	if err != nil {
		return err
	}
	return ap.applyInclude(ctx, LocationsFile(ap.cfg.RunDir), "SVNGO_SVN_LOCATIONS_CONF", []byte(conf))
}
