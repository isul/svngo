func TestSvnAccessConf(t *testing.T) {
	if got := SvnAccessConf(ipacl.List{}); strings.Contains(got, "Rewrite") {
		t.Fatalf("empty list produced rules: %q", got)
	}
	got := SvnAccessConf(ipacl.MustParse("192.168.1.0/24\n10.0.0.5\n2001:db8::/48"))
	want := "# Generated by SvnGo - SVN client IP allow list. Do not edit.\n" +
		"RewriteCond expr \"! -R '127.0.0.0/8'\"\n" +
		"RewriteCond expr \"! -R '::1/128'\"\n" +
		"RewriteCond expr \"! -R '192.168.1.0/24'\"\n" +
		"RewriteCond expr \"! -R '10.0.0.5/32'\"\n" +
		"RewriteCond expr \"! -R '2001:db8::/48'\"\n" +
		"RewriteRule \"^/(?!admin(?:/|$)).\" - [F,L]\n"
	if got != want {
		t.Fatalf("SvnAccessConf:\n%s\nwant:\n%s", got, want)
	}
}

func fakeHttpd(t *testing.T, script string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "httpd")
	if err := os.WriteFile(p, []byte("#!/bin/sh\n"+script+"\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestApplySvnAccess(t *testing.T) {
	run := t.TempDir()
	cfg := &config.Config{RunDir: run, ApacheConf: filepath.Join(run, "httpd.conf")}
	if err := WriteSvnAccess(run, ipacl.List{}); err != nil {
		t.Fatal(err)
	}
	live := AccessFile(run)

	// the test run must see the new rules through SVNGO_SVN_ACCESS_CONF
	out := filepath.Join(t.TempDir(), "seen")
	cfg.ApacheBin = fakeHttpd(t, `cat "$SVNGO_SVN_ACCESS_CONF" > `+out)
	ap := New(cfg, logring.New(10))
	list := ipacl.MustParse("192.0.2.0/24")
	if err := ap.ApplySvnAccess(context.Background(), list); err != nil {
		t.Fatal(err)
	}
	seen, _ := os.ReadFile(out)
	now, _ := os.ReadFile(live)
	if string(now) != SvnAccessConf(list) || string(seen) != string(now) {
		t.Fatalf("live=%q tested=%q", now, seen)
	}
	if _, err := os.Stat(live + ".new"); !os.IsNotExist(err) {
		t.Fatal("temporary rules file left behind")
	}

	// a failing test leaves the live file untouched
	cfg.ApacheBin = fakeHttpd(t, "echo broken; exit 1")
	ap = New(cfg, logring.New(10))
	err := ap.ApplySvnAccess(context.Background(), ipacl.MustParse("198.51.100.1"))
	if err == nil || !strings.Contains(err.Error(), "broken") {
		t.Fatalf("expected config test failure, got %v", err)
	}
	if b, _ := os.ReadFile(live); string(b) != string(now) {
		t.Fatal("live rules changed after a failed test")
	}

	// unchanged rules skip the test entirely
	if err := ap.ApplySvnAccess(context.Background(), list); err != nil {
		t.Fatalf("unchanged rules re-tested: %v", err)
	}
}
