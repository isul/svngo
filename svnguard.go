package main

import (
	"context"
	"log/slog"
	"net"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"sync"
	"time"
)

// SVN Basic authentication is handled by Apache, so brute-force protection
// works fail2ban-style: Apache logs every failed login (401 with a user name)
// on a dedicated line, svnGuard counts failures per client IP and, past the
// threshold, writes the IP into a RewriteMap file. Apache consults that map in
// the translate phase - before authentication runs - and answers 429, so a
// blocked client cannot even test passwords. The map is re-read by mod_rewrite
// whenever its mtime changes, which needs no Apache restart.

const svnBlockFile = "svn-blocked.map"

type BlockedIP struct {
	IP    string
	Until time.Time
	Fails int
}

type svnGuard struct {
	file    string
	limits  func() (attempts int, window time.Duration) // attempts 0 = disabled
	onBlock func(ip string, fails int)

	mu      sync.Mutex
	fails   map[string]*attempt
	blocked map[string]BlockedIP
}

func newSVNGuard(runDir string, limits func() (int, time.Duration), onBlock func(string, int)) (*svnGuard, error) {
	g := &svnGuard{file: filepath.Join(runDir, svnBlockFile), limits: limits, onBlock: onBlock,
		fails: map[string]*attempt{}, blocked: map[string]BlockedIP{}}
	g.mu.Lock()
	defer g.mu.Unlock()
	return g, g.writeLocked()
}

// Fail records one failed SVN login from ip (as printed by Apache's %a).
func (g *svnGuard) Fail(ip string) {
	addr := net.ParseIP(ip)
	if addr == nil || addr.IsLoopback() {
		return
	}
	max, window := g.limits()
	if max <= 0 {
		return
	}
	now := time.Now()
	g.mu.Lock()
	if b, ok := g.blocked[ip]; ok && now.Before(b.Until) {
		g.mu.Unlock()
		return
	}
	if len(g.fails) > 10000 {
		for k, at := range g.fails {
			if now.Sub(at.first) > window {
				delete(g.fails, k)
			}
		}
	}
	at := g.fails[ip]
	if at == nil || now.Sub(at.first) > window {
		at = &attempt{first: now}
		g.fails[ip] = at
	}
	at.count++
	if at.count < max {
		g.mu.Unlock()
		return
	}
	n := at.count
	delete(g.fails, ip)
	g.blocked[ip] = BlockedIP{IP: ip, Until: now.Add(window), Fails: n}
	err := g.writeLocked()
	g.mu.Unlock()
	if err != nil {
		slog.Error("SVN 차단 목록 기록 실패", "err", err)
	}
	slog.Warn("SVN 로그인 실패 누적으로 IP 를 차단했습니다", "ip", ip, "fails", n, "until", now.Add(window).Format(time.DateTime))
	if g.onBlock != nil {
		g.onBlock(ip, n)
	}
}

// Unblock lifts a block (and forgets counted failures) for ip.
func (g *svnGuard) Unblock(ip string) (bool, error) {
	g.mu.Lock()
	defer g.mu.Unlock()
	_, ok := g.blocked[ip]
	delete(g.blocked, ip)
	delete(g.fails, ip)
	if !ok {
		return false, nil
	}
	return true, g.writeLocked()
}

// List returns active blocks, soonest expiry first.
func (g *svnGuard) List() []BlockedIP {
	g.mu.Lock()
	defer g.mu.Unlock()
	now := time.Now()
	res := make([]BlockedIP, 0, len(g.blocked))
	for _, b := range g.blocked {
		if now.Before(b.Until) {
			res = append(res, b)
		}
	}
	sort.Slice(res, func(i, j int) bool { return res[i].Until.Before(res[j].Until) })
	return res
}

// Prune drops expired blocks and stale counters, rewriting the map if needed.
func (g *svnGuard) Prune() error {
	_, window := g.limits()
	g.mu.Lock()
	defer g.mu.Unlock()
	now := time.Now()
	changed := false
	for ip, b := range g.blocked {
		if !now.Before(b.Until) {
			delete(g.blocked, ip)
			changed = true
		}
	}
	for ip, at := range g.fails {
		if now.Sub(at.first) > window {
			delete(g.fails, ip)
		}
	}
	if !changed {
		return nil
	}
	return g.writeLocked()
}

func (g *svnGuard) Run(ctx context.Context) {
	t := time.NewTicker(20 * time.Second)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			if err := g.Prune(); err != nil {
				slog.Error("SVN 차단 목록 정리 실패", "err", err)
			}
		}
	}
}

func (g *svnGuard) writeLocked() error {
	ips := make([]string, 0, len(g.blocked))
	for ip := range g.blocked {
		ips = append(ips, ip)
	}
	sort.Strings(ips)
	var b strings.Builder
	b.WriteString("# Generated by SvnGo - blocked SVN clients (RewriteMap txt)\n")
	for _, ip := range ips {
		b.WriteString(ip + " " + strconv.FormatInt(g.blocked[ip].Until.Unix(), 10) + "\n")
	}
	return atomicWrite(g.file, []byte(b.String()))
}
